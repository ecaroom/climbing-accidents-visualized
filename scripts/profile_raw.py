"""Profile data/raw exports -> data/PROFILE.md. Read-only: no cleaning, just
describes what is there. Rerun: .venv/bin/python scripts/profile_raw.py"""
import pathlib, re, pandas as pd, numpy as np
ROOT = pathlib.Path(__file__).resolve().parent.parent
RAW = ROOT / "data" / "raw"
df = pd.read_csv(RAW / "accidents__00_data.csv", dtype=str, keep_default_na=False)
defs = pd.read_csv(RAW / "definitions__00_definitions_dictionaries.csv", dtype=str, keep_default_na=False)
cols = list(df.columns); TAGCOLS = cols[7:]
out = []; P = out.append

def esc(s, n=50):
    s = str(s).replace("\n", "⏎").replace("|", "\\|")
    return s if len(s) <= n else s[:n - 1] + "…"

def infer_type(s):
    nn = s[s != ""]
    if nn.empty: return "empty"
    if nn.str.fullmatch(r"-?\d+").all(): return "integer"
    if pd.to_numeric(nn, errors="coerce").notna().all(): return "float"
    if TAGCOLS.count(s.name) and nn.isin(["1","2","3","4","5","6","25","Y"]).all(): return "flag/count (mixed str)"
    return "text"

# ---- families from the definitions sheet (section header rows have empty col A)
fam, cur = {}, None
for _, r in defs.iterrows():
    name = r["Category Name"]
    if not name: continue
    if r["AAC Category"] == "" and all(r[c] == "" for c in defs.columns[2:7]): cur = name; continue
    fam[name.strip()] = cur
def_names = set(fam)
data_names = {c.strip() for c in TAGCOLS}
ALIASES = {"Severe Weather / Act of God": "Severe Weather"}
col_family = {}
for c in TAGCOLS:
    k = c.strip()
    inv = {v: k2 for k2, v in ALIASES.items()}
    col_family[c] = fam.get(k) or fam.get(inv.get(k, "")) or "(not in definitions)"

num = df[TAGCOLS].replace({"": "0", "Y": "1"}).apply(pd.to_numeric)
flag = num > 0
climb = ~flag["Non-climbing"]

# ================= HEADER =================
P("# PROFILE — raw AAC accident data (before any cleaning)\n")
P("Generated by `scripts/profile_raw.py` from `data/raw/` (which `scripts/export_raw.py` builds from `source/`).\n")
P("## Files exported to data/raw/\n")
for f in sorted(RAW.glob("*")):
    P(f"- `{f.name}`" + (f" — {sum(1 for _ in open(f, encoding='utf-8'))} lines" if f.suffix == ".csv" else ""))
P("\n`*__formulas.csv` = same grid with formula text instead of cached values (array formulas wrapped in `{}`). "
  "Pivot sheets (`pt*`) are exported as raw grids starting at A1: their real header rows are on rows 3–12, not row 1.\n")

P("## Workbook structure notes\n")
P("""**_github-AAC_accidents_tagged_data.xlsx** — 10 sheets, all visible. No merged cells, hidden rows or hidden columns anywhere.
- `data` (A1:CR2771): header on row 1, 2,770 data rows, 96 columns, autofilter on, frozen at A2.
  - Col A `Search Column` = 2,769 **array formulas** (`=SUMPRODUCT(--ISNUMBER(SEARCH({"stranding","stranded"},E2)))`), a leftover keyword-search helper; cached values 0/1/2. Header has trailing `\\n\\n`.
  - Col G `COUNT OF TAGS` = 2,769 formulas `=SUM(P:CF)` (experience → miscommunication; excludes age H:O and months CG:CR). Cached values match a recomputation on 100% of rows.
  - Row 2771 (ID `997tt`) has **literal values** in A and G, not formulas.
- `pt1`…`pt7`, `ptA`: Excel **pivot tables** + derived % formulas (e.g. `=F11/$F$59`). Header rows are on rows 3–12 with filter fields above them, and pivot-filter notes in free text. They are outputs, not inputs; useful only as cross-checks of published numbers. `pt2!E6` uses `GETPIVOTDATA`.

**_github-Category-Definitions+Notes.xlsx** — 1 visible sheet `definitions+dictionaries` (A1:H99), header row 1, frozen at A2.
- 9 **merged ranges** (B:G) on rows 2, 10, 15, 20, 34, 41, 46, 54, 86 — these are the section header rows (Age, Experience Level, Outcome, Type of Climbing, …). In the CSV the label sits in col B with the rest blank.
- `Dictionary 1 (Title)` / `Dictionary 2 (Description)` are mostly **array formulas** whose search terms live only in the formula text and whose references are broken (`#REF!`), so cached values are just 0/False. **The keyword dictionaries are only recoverable from `definitions__00_definitions_dictionaries__formulas.csv`.**
- Col H is an unnamed, all-blank column.

**_github-uncut-methodology.docx** → `methodology.md`: 21k chars, starts with a table of contents (page numbers kept as text), no tables, 1 inline image (not extracted). Bullets in the doc use literal `●` characters in some places, which are preserved.
""")

# ================= COUNTS =================
yr = pd.to_numeric(df["Publication Year"], errors="coerce")
P("## Row counts\n")
P(f"| subset | rows |\n|---|---|\n| total (`data` sheet) | {len(df):,} |\n| tagged `Non-climbing` | {int(flag['Non-climbing'].sum())} |\n| **climbing-only** | **{int(climb.sum()):,}** |\n")
P(f"Publication year range: **{int(yr.min())}–{int(yr.max())}** (30 years). One row has a blank year: ID `{df.loc[yr.isna(),'ID'].iloc[0]}` (Red River Gorge). Climbing-only range is the same.\n")
P("IDs are unique strings (not integers): suffix `t` = truncated narrative (105), `a/b/c/d/f/aa/ab` = incident split out of a shared report (per methodology). Sort as strings, not numbers.\n")
P("Rows per publication year:\n")
yc = df["Publication Year"].value_counts().sort_index()
P("| " + " | ".join(yc.index.map(lambda x: x or "(blank)")) + " |\n|" + "---|" * len(yc) + "\n| " + " | ".join(map(str, yc.values)) + " |\n")

# ================= HOW TAGS ARE STORED =================
ta_mism = []
non_age_month = [c for c in TAGCOLS if col_family[c] not in ("Age", "Months") and c.strip() != ">75"]
for i, r in df.iterrows():
    s = {t.strip() for t in r["Tags Applied"].split(",") if t.strip()}
    f = {c.strip() for c in non_age_month if flag.at[i, c]}
    if s != f: ta_mism.append((r["ID"], sorted(s - f), sorted(f - s)))
P("## How tags are stored\n")
P(f"""**One column per tag (wide, 89 tag columns H:CR)**, plus a redundant comma-delimited text column `Tags Applied`.
- Blank = not tagged. Otherwise the cell is usually `1`.
- **Age columns (H:O) hold a count of climbers in that age band**, not a flag: values 1–6, and one `25` (ID `166`, col `15-20` — probably a group; worth checking). 457 age cells are >1. `>75` is set on only 2 rows (IDs `590`, `2515b`).
- **Month columns (CG:CR) contain `Y` in 28 cells** instead of `1` (IDs like `2502t`, `2637f`, `34a`). Treated as 1 here.
- All other tag columns contain only blank or `1`.
- `Tags Applied` lists every flagged tag **except age and month tags**. Excluding those, it disagrees with the flag columns on **{len(ta_mism)}** rows, {'**all** of them' if all(b==['Aid & Big Wall'] and c==['Aid & Big Wall Climbing'] for _,b,c in ta_mism) else 'NOT all'} because the text abbreviates `Aid & Big Wall Climbing` as `Aid & Big Wall`. Otherwise text and flags agree exactly, so the flag columns are the source of truth.
- `COUNT OF TAGS` = number of non-age, non-month tags.
- **Yes, one accident can carry multiple disciplines and multiple factors.** See counts below. The methodology also says every tag is a contributing factor; there is **no "primary" or "immediate cause" field** anywhere in the data.
""")

# ================= FAMILIES =================
P("## Tag families (from section headers in the definitions file)\n")
P("Counts per accident of how many tags in each family are set. Climbing-only rows (n=%d).\n" % climb.sum())
families = {}
for c in TAGCOLS: families.setdefault(col_family[c], []).append(c)
DISC = ["Trad Climbing", "Sport", "Top-Rope", "Aid & Big Wall Climbing", "Bouldering", "Alpine/Mountaineering", "Ice Climbing"]
families["(derived) Discipline only — Trad/Sport/TR/Aid/Boulder/Alpine/Ice"] = DISC
families["(derived) All factor families combined"] = [c for c in TAGCOLS if col_family[c] in
    ("Alpine & Ice Climbing Factors", "Natural Factors", "Alpine & Ice Climbing Natural Factors", "Human Factors")]
P("| family | columns | 0 tags | 1 | 2 | 3+ |\n|---|---|---|---|---|---|")
for fname, cs in families.items():
    n = flag.loc[climb, cs].sum(axis=1)
    b = [int((n == 0).sum()), int((n == 1).sum()), int((n == 2).sum()), int((n >= 3).sum())]
    P(f"| {fname} | {len(cs)} | " + " | ".join(f"{x:,} ({x/climb.sum():.0%})" for x in b) + " |")
P("")
P("Family membership:\n")
for fname, cs in families.items():
    if fname.startswith("(derived)"): continue
    P(f"- **{fname}**: " + ", ".join(f"`{c}`" for c in cs))
P("")

# outcomes + discipline combos
o = flag.loc[climb, ["Deadly", "Serious", "Minor"]]
P("### Outcome combinations (climbing-only)\n")
P("Outcome is *not* exclusive per accident — it is per climber, so a party can have Deadly + Serious. There is **no explicit 'no injury' tag**; rows with none of Deadly/Serious/Minor are effectively 'no injury or unreported'.\n")
P("| Deadly | Serious | Minor | accidents |\n|---|---|---|---|")
for k, v in o.value_counts().items(): P(f"| {'✓' if k[0] else ''} | {'✓' if k[1] else ''} | {'✓' if k[2] else ''} | {v:,} |")
P("")
P("### Most common discipline combinations (climbing-only, top 20)\n")
combo = flag.loc[climb, DISC].apply(lambda r: " + ".join(c for c in DISC if r[c]) or "(none)", axis=1)
P("| combination | accidents |\n|---|---|")
for k, v in combo.value_counts().head(20).items(): P(f"| {k} | {v:,} |")
P(f"\n{combo.nunique()} distinct combinations in total.\n")
P("### Other climbing-mode tags (not disciplines, but candidates for an 'other' bucket)\n")
P("| tag | climbing accidents |\n|---|---|")
for c in ["Roped", "Unroped ", "Solo", "Climbing Alone", "Descent", "Pendulum", "Glissading", "Ski-related ", "Gym / Artificial"]:
    P(f"| `{c}` | {int(flag.loc[climb, c].sum()):,} |")
P("")

# ================= CROSS-CHECK =================
P("## Tag names: data vs. Category Definitions\n")
only_data = sorted(c for c in data_names if c not in def_names and c not in ALIASES.values())
only_defs = sorted(c for c in def_names if c not in data_names and c not in ALIASES)
P("| issue | detail |\n|---|---|")
P(f"| In data, not in definitions | {', '.join(f'`{x}`' for x in only_data) or 'none'} |")
P(f"| In definitions, not in data | {', '.join(f'`{x}`' for x in only_defs) or 'none'} |")
P("| Name differs | definitions `Severe Weather / Act of God` ↔ data `Severe Weather` |")
P("| Trailing whitespace in data header | `Unroped `, `Ski-related ` (definitions also has `Ski-related `) |")
P("| Typo kept in both | `Crevasse / Moat / Berschrund` (Bergschrund is also its own tag) |")
P("| Section placement | `Pendulum` sits among climbing-type columns in data but under Human Factors in definitions |")
P("")

# ================= COLUMN PROFILE =================
P("""## Gotchas to resolve before cleaning (not acted on yet)

1. No primary-factor field: every tag is a co-equal contributing factor (methodology). Any "primary factor" stage must be derived or avoided.
2. 312 climbing accidents (11%) have **no discipline tag** among Trad/Sport/TR/Aid/Boulder/Alpine/Ice; 277 have 2+.
3. Outcome is per climber, not per accident: 113 climbing accidents carry 2+ of Deadly/Serious/Minor; 189 carry none (no explicit "no injury" tag).
4. `Experience: Unknown` is set on only 20 rows, although the definitions say it "includes all untagged incidents" — 55% of climbing rows have no experience tag at all.
5. Age cells are headcounts (one `25`); month cells mix `1` and `Y`; one row has 2 months; one row has a blank publication year.
6. Header whitespace (`Unroped `, `Ski-related `, `Search Column\\n\\n`) and name drift (`Severe Weather` vs `Severe Weather / Act of God`, `Aid & Big Wall` in `Tags Applied`).
7. Col A `Search Column` and col G `COUNT OF TAGS` are derived helper columns, not data.
""")
P("## Every column — `data` sheet\n")
P("Null = empty cell. Top values are as-exported strings (⏎ = newline; long text truncated).\n")
P("| # | column | type | null % | distinct | top 10 values (count) |\n|---|---|---|---|---|---|")
for i, c in enumerate(cols):
    s = df[c]
    vc = s[s != ""].value_counts().head(10)
    top = "; ".join(f"{esc(k, 40)} ({v})" for k, v in vc.items())
    P(f"| {i+1} | `{esc(c,40)}` | {infer_type(s)} | {(s=='').mean():.2%} | {s[s!=''].nunique():,} | {top} |")
P("")
P("## Every column — definitions sheet\n")
P("| # | column | null % | distinct | top values |\n|---|---|---|---|---|")
for i, c in enumerate(defs.columns):
    s = defs[c]; vc = s[s != ""].value_counts().head(10)
    P(f"| {i+1} | `{esc(c,40) or '(unnamed)'}` | {(s=='').mean():.1%} | {s[s!=''].nunique()} | " + "; ".join(f"{esc(k,30)} ({v})" for k, v in vc.items()) + " |")
P("\nPivot sheets (`pt*`) are not profiled column-by-column: they are summary outputs with headers on rows 3–12.\n")

(ROOT / "data" / "PROFILE.md").write_text("\n".join(out), encoding="utf-8")
print("wrote data/PROFILE.md;", len(ta_mism), "Tags Applied mismatches")
